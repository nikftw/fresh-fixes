# Builds FreshFixes/Modules/MapIcons.lua from Leatrix Maps' Forever icon list
# (Leatrix_Maps_Icons.lua from the WoW Forever / _classic_beta_ install).
#   pip install lupa
#   python import_leatrix_icons.py <Leatrix_Maps_Icons.lua> <output lua>
# Flight points are left out: those come from Blizzard data (gen_mapdata.py).
import sys
from lupa import lua51

src, out = sys.argv[1], sys.argv[2]
lua = lua51.LuaRuntime()
lua.execute("""
GetBuildInfo = function() return "1.60.1", "70291", "", 16001 end
""")
load = lua.eval("""
function(code)
    local ns = { L = setmetatable({}, { __index = function(_, k) return k end }) }
    local f = assert(loadstring(code))
    f("Leatrix_Maps", ns)
    return ns.Icons
end
""")
code = open(src, encoding="utf-8-sig").read()   # strips the BOM Lua 5.1 can't read
icons = load(code)

KIND = {
    "Spirit": ("Spirit", "N"), "Arrow": ("Arrow", "N"),
    "Dungeon": ("Dungeon", "N"), "Raid": ("Raid", "N"), "Dunraid": ("Dungeon", "N"),
    "PortalA": ("Portal", "A"), "PortalH": ("Portal", "H"), "PortalN": ("Portal", "N"),
    "TravelA": ("Boat", "A"), "TravelH": ("Boat", "H"), "TravelN": ("Boat", "N"),
}

def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'

rows, skipped, total = {}, 0, 0
for mapID in sorted(icons.keys()):
    entries = []
    for e in icons[mapID].values():
        kind = e[1]
        if kind not in KIND:
            skipped += 1     # flight points etc.
            continue
        ours, faction = KIND[kind]
        name = e[4] or ""
        desc = e[5]
        if ours == "Boat":
            low = name.lower()
            if "zeppelin" in low:
                ours = "Zeppelin"
            elif "tram" in low:
                ours = "Tram"
        if ours in ("Dungeon", "Raid") and e[7] and e[8]:
            desc = f"{desc or ours} ({int(e[7])}-{int(e[8])})"
        rot = e[12] if ours == "Arrow" and e[12] else 0
        link = int(e[13]) if e[13] else 0          # map to open when clicked
        entries.append((ours, faction, float(e[2]) / 100, float(e[3]) / 100, name, desc, float(rot), link))
        total += 1
    if entries:
        rows[int(mapID)] = entries

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("local _, FF = ...\n\n")
    f.write("-- Hand-placed map icons (spirit healers, boats/zeppelins/trams, portals,\n")
    f.write("-- zone crossings, dungeon and raid entrances) from Leatrix Maps for WoW Forever.\n")
    f.write("-- Generated by tools/import_leatrix_icons.py - do not edit by hand.\n")
    f.write("-- [uiMapID] = { { kind, faction A/H/N, x, y, name, description, arrowRotation, linkedMapID }, ... }\n")
    f.write("FF.MapZoneIcons = {\n")
    for mapID, entries in rows.items():
        f.write(f"    [{mapID}] = {{\n")
        for k, fa, x, y, name, desc, rot, link in entries:
            f.write(f"        {{ {q(k)}, {q(fa)}, {x:.4f}, {y:.4f}, {q(name)}, {q(desc) if desc else 'nil'}, {rot:g}, {link} }},\n")
        f.write("    },\n")
    f.write("}\n")
print(f"maps: {len(rows)}, icons: {total}, skipped (flight points etc.): {skipped}")
